# 1. User Input & Data Type Casting (String to Float)
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

# 2. Arithmetic Operator (Addition)
sum_result = num1 + num2

# 3. Arithmetic Operator (Multiplication)
prod_result = num1 * num2

# Outputting results
print(f"The addition result (Float Data Type): {sum_result}")
print(f"The multiplication result (Float Data Type): {prod_result}")